/* Necessary rational class conditions on lower-level X1 curves.
   The bases must have rational Jacobians generated by rational cusp classes.
   Every finite-field cusp complement is allowed, providing an overestimate. */
Attach("common/class_rational_reduction.m");
if not assigned BaseNs then BaseNs:=[24,16];
elif Type(BaseNs) eq MonStgElt then
 BaseNs:=[StringToInteger(a):a in Split(BaseNs,",")];
end if;
procedure QuotientCuspClasses(weights,classes,remaining,start,current,~out)
 if remaining eq 0 then Include(~out,current);return;end if;
 for i in [start..#weights] do
  if weights[i] le remaining then
   QuotientCuspClasses(weights,classes,remaining-weights[i],i,
                       current+classes[i],~out);
  end if;
 end for;
end procedure;
QData:=[* *];QClassCache:=AssociativeArray();
for bn in BaseNs do
 assert N mod bn eq 0 and GCD(p,bn) eq 1;
 Y:=MDX1(bn,GF(p));CY:=Curve(Y);csY:=Cusps(Y);
 c0Y:=[c:c in csY|Degree(c) eq 1][1];
 GY,iY,mY:=ClassGroupRationalReduction(CY,c0Y:Proof:=true);
 qsY:=[Type(o) eq PlcCrvElt select Divisor(o) else o:o in CuspOrbitsQ(Y)];
 HY:=sub<GY|[mY(o-Degree(o)*Divisor(c0Y)):o in qsY]>;
 QY,qY:=quo<GY|HY>;
 ccY:=[qY(mY(Divisor(c)-Degree(c)*Divisor(c0Y))):c in csY];
 compsY:=AssociativeArray();
 for k in [0..D] do
  vals:={QY|};
  QuotientCuspClasses([Degree(c):c in csY],ccY,k,1,QY!0,~vals);
  compsY[k]:=vals;
 end for;
 Append(~QData,<Y,GY,mY,QY,qY,c0Y,compsY>);
 printf "QUOTIENT_SETUP level=%o genus=%o classgroup=%o rational_cusp_image=%o quotient=%o complement_counts=%o time=%o\n",
        bn,Genus(Y),Invariants(GY),Invariants(HY),Invariants(QY),
        [#compsY[k]:k in [0..D]],Cputime(t0);
end for;
procedure QuotientCheck(X,Dv,degree,~cache,~reject,~outlevel)
 reject:=false;outlevel:=0;
 ps,ms:=Support(Dv);
 for bi in [1..#QData] do
  Y,GY,mY,QY,qY,c0Y,compsY:=Explode(QData[bi]);
  a:=QY!0;
  for pi in [1..#ps] do
   key:=<bi,ps[pi]>;
   if not IsDefined(cache,key) then
    E:=EllipticCurve(X,ps[pi]);ls:=LevelStructure(X,ps[pi]);
    P:=ls`P;
    assert N*P eq E!0;
    assert &and[(N div ell)*P ne E!0:ell in PrimeDivisors(N)];
    smallls:=DegeneracyMap(X,N div Level(Y),ls);
    yy:=ModuliPointCyclicCommonZeros(Y,E,smallls);
    assert not IsCusp(Y,yy) and Degree(ps[pi]) mod Degree(yy) eq 0;
    weight:=Degree(ps[pi]) div Degree(yy);
    cache[key]:=qY(weight*mY(Divisor(yy)-Degree(yy)*Divisor(c0Y)));
   end if;
   a+:=ms[pi]*cache[key];
  end for;
  if -a notin compsY[D-degree] then reject:=true;outlevel:=Level(Y);return;end if;
 end for;
 end procedure;
print "QUOTIENT_PREFILTER_READY complete=true";
