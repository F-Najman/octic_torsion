// placecounts8.m -- independent count of noncuspidal closed places on modular curves over F_q.
// Method: enumerate every elliptic curve over F_{q^e} (all j-invariants, all twists, one j per
// Frobenius orbit weighted by the orbit length), take the exact group structure Z/a x Z/b, and
// count isomorphism classes of level structures:
//   X1(n)          : #{P of exact order n}/#Aut_{F_{q^e}}(E)
//   X1(m,n), m>1   : m*#{Q of exact order n}/#Aut  if E[m] is rational (fixed Weil pairing, q = 1 mod m)
//                    [#injective pairs (P,Q) = m*phi(m)*#{Q}; a fixed pairing value takes 1/phi(m) of them]
//   "X1(n),E[m]"   : X1(n) restricted to curves with E[m] rational (encoded m<0)
//   "div M"        : only lists curves with M | #E (encoded m=0)
// Aut acts freely on level structures containing a point of order >= 5 (deg(u-1) <= 4 for u != 1);
// this is asserted (divisibility).  Twists and Aut over the base field are validated by the mass
// formula  sum_{twists} 1/#Aut = 1  at j = 0, 1728.  Closed places of degree d by Moebius inversion.
// Parameters: q, D, S = "1:38,2:26,-5:25,0:81" (m:n pairs), optional X27:=1 for the detailed
// X1(27)/X1(54) analysis over F_5 (Prop. 3.13).
SetColumns(0); SetMemoryLimit(12*10^9);
if Type(q) eq MonStgElt then q:=StringToInteger(q); end if;
if Type(D) eq MonStgElt then D:=StringToInteger(D); end if;
if not assigned X27 then X27:=0; elif Type(X27) eq MonStgElt then X27:=StringToInteger(X27); end if;
specs:=[ [StringToInteger(t): t in Split(s,":")] : s in Split(S,",")];
p:=Factorization(q)[1][1];
function exact(a,b,n) return &+[ MoebiusMu(n div e)*Gcd(a,e)*Gcd(b,e) : e in Divisors(n)]; end function;
function contrib(sp,a,b,aut)
  m:=sp[1]; n:=sp[2];
  if m eq 1 then c:=exact(a,b,n);
  elif m gt 1 then if a mod m ne 0 then return 0; end if; c:=m*exact(a,b,n);
  elif m lt 0 then if a mod (-m) ne 0 then return 0; end if; c:=exact(a,b,n);
  else return 1; end if;
  if c eq 0 then return 0; end if;
  assert c mod aut eq 0; return c div aut;
end function;
function need(sp,N) m:=sp[1]; n:=sp[2];
  if m eq 0 then return N mod n eq 0; elif m gt 0 then return N mod (m*n) eq 0; else return N mod ((-m)*n) eq 0; end if; end function;
function spname(sp) m:=sp[1]; n:=sp[2];
  if m eq 1 then return Sprintf("X1(%o)",n); elif m gt 1 then return Sprintf("X1(%o,%o)",m,n);
  elif m lt 0 then return Sprintf("X1(%o)[E[%o] rational]",n,-m); else return Sprintf("div %o",n); end if; end function;
// Tate normal form (b,c) of (E,Q), Q of order >= 4 (from the degree-7 review helpers)
function tate(E,Q)
  k:=BaseRing(E); a1,a2,a3,a4,a6:=Explode(aInvariants(E)); x0:=Q[1]; y0:=Q[2];
  R<X,Y>:=PolynomialRing(k,2); f:=Y^2+a1*X*Y+a3*Y-(X^3+a2*X^2+a4*X+a6);
  g:=Evaluate(f,[X+x0,Y+y0]); assert MonomialCoefficient(g,R!1) eq 0;
  A3:=MonomialCoefficient(g,Y); A4:=-MonomialCoefficient(g,X); assert A3 ne 0;
  g:=Evaluate(g,[X,Y+(A4/A3)*X]); assert MonomialCoefficient(g,X) eq 0;
  A1:=MonomialCoefficient(g,X*Y); A2:=-MonomialCoefficient(g,X^2); A3:=MonomialCoefficient(g,Y);
  return -A2^3/A3^2, 1-A1*A2/A3;
end function;
function ptdeg(b,c,e) // degree over F_q of the field generated by b,c in F_{q^e}
  for f in Divisors(e) do if b^(q^f) eq b and c^(q^f) eq c then return f; end if; end for; end function;
function key(b,c,f) // canonical key of the closed point: min over Frobenius conjugates of the coefficient vectors
  ks:=[ [Integers()!z : z in Eltseq(b^(q^i),GF(p))] cat [Integers()!z : z in Eltseq(c^(q^i),GF(p))] : i in [0..f-1]];
  return Min(ks); end function;

cnt:=AssociativeArray(); qual:=AssociativeArray();
for sp in specs do for e in [1..D] do cnt[<sp,e>]:=0; qual[<sp,e>]:={* *}; end for; end for;
A27:=AssociativeArray(); // <e,k> -> weighted F_{q^e}-points of X1(27) of exact degree e with k nonzero rational 2-torsion points
ORB:=AssociativeArray();  // e -> list of <k, set of closed-point keys of one diamond orbit>
masserr:=0; t0:=Cputime();
for e in [1..D] do
  K:=GF(q^e); qe:=q^e; visited:={K|}; norb:=0;
  if X27 eq 1 then for k in [0,1,3] do A27[<e,k>]:=0; end for; ORB[e]:=[]; seen:={}; end if;
  for j in K do
    if j in visited then continue; end if;
    conj:={j^(q^i): i in [0..e-1]}; o:=#conj; visited join:=conj; norb+:=1;
    E0:=EllipticCurveWithjInvariant(j);
    if j eq 0 or j eq K!1728 then
      Ts:=Twists(E0); auts:=[#AutomorphismGroup(T): T in Ts]; Ns:=[#T: T in Ts];
      if &+[1/x: x in auts] ne 1 then masserr+:=1; print "MASS_ERROR", q, e, j; end if;
    else
      Ts:=[E0, QuadraticTwist(E0)]; N0:=#E0; Ns:=[N0, 2*(qe+1)-N0]; auts:=[2,2];
      if qe le 6561 then assert #Ts[2] eq Ns[2] and not IsIsomorphic(Ts[1],Ts[2]); end if;
    end if;
    for i in [1..#Ts] do
      T:=Ts[i]; N:=Ns[i]; aut:=auts[i];
      rel:=[sp: sp in specs | need(sp,N)];
      if #rel eq 0 then continue; end if;
      G,mG:=AbelianGroup(T); assert #G eq N;
      inv:=Invariants(G); a:=#inv eq 2 select inv[1] else 1; b:=#inv eq 0 select 1 else inv[#inv];
      for sp in rel do
        c:=contrib(sp,a,b,aut);
        if c gt 0 then
          if sp[1] ne 0 then cnt[<sp,e>]+:=o*c; end if;
          Include(~qual[<sp,e>], <N, inv, o, aut>);  // multiplicity per Frobenius-orbit representative
        end if;
      end for;
      if X27 eq 1 and N mod 27 eq 0 then
        k:=Gcd(a,2)*Gcd(b,2)-1;
        ex:=exact(a,b,27);
        if ex gt 0 then
          if o eq e and not (e in [2,3,4,5,6]) then
            A27[<e,k>]+:=o*(ex div aut);   // j generates F_{q^e}: every point has exact degree e
          else // explicit points: exact degree via Tate normal form; diamond orbits on closed points
            pts:=[mG(g): g in G | Order(g) eq 27]; assert #pts eq ex;
            good:=0;
            for P in pts do
              bb,cc:=tate(T,P); f:=ptdeg(bb,cc,e);
              if f ne e then continue; end if;
              good+:=1; kk:=key(bb,cc,e);
              if not kk in seen then
                orb:={}; for d in [1,2,4,5,7,8,10,11,13] do b2,c2:=tate(T,d*P); Include(~orb, key(b2,c2,e)); end for;
                seen join:=orb; Append(~ORB[e], <k, #orb>);
              end if;
            end for;
            assert good mod aut eq 0; A27[<e,k>]+:=o*(good div aut);
          end if;
        end if;
      end if;
    end for;
  end for;
  printf "FIELD q=%o e=%o orbits=%o cputime=%o\n", q, e, norb, Cputime(t0);
end for;
print "MASS_ERRORS", masserr;
for sp in specs do
  if sp[1] eq 0 then
    for e in [1..D] do if #qual[<sp,e>] gt 0 then printf "DIV %o over F_%o^%o: curves (N, invariants, j-orbit length, #Aut) %o\n", sp[2], q, e, qual[<sp,e>]; end if; end for;
    continue;
  end if;
  pts:=[cnt[<sp,e>]: e in [1..D]];
  places:=[]; for d in [1..D] do s:=&+[MoebiusMu(d div e)*pts[e] : e in Divisors(d)]; assert s mod d eq 0; Append(~places, s div d); end for;
  printf "POINTS %o q=%o: %o\n", spname(sp), q, pts;
  printf "PLACES %o q=%o: %o\n", spname(sp), q, places;
  for e in [1..D] do if #qual[<sp,e>] gt 0 and #qual[<sp,e>] le 40 then
    printf "QUAL %o q=%o e=%o: #iso classes of curves=%o; (N, invariants, j-orbit length, #Aut) %o\n", spname(sp), q, e, &+[t[3]: t in qual[<sp,e>]], qual[<sp,e>]; end if; end for;
end for;
if X27 eq 1 then
  for e in [1..D] do
    printf "X27 e=%o closed points of X1(27) of exact degree e with k nonzero rational 2-torsion pts: k=0:%o k=1:%o k=3:%o (k>=1: %o)\n", e,
      A27[<e,0>]/e, A27[<e,1>]/e, A27[<e,3>]/e, (A27[<e,1>]+A27[<e,3>])/e;
    if #ORB[e] gt 0 then
      for k in [0,1,3] do L:=[t[2]: t in ORB[e] | t[1] eq k]; if #L gt 0 then printf "X27ORB e=%o k=%o: %o diamond orbits, sizes %o\n", e, k, #L, {* x: x in L *}; end if; end for;
      printf "X27ORB e=%o k>=1: %o diamond orbits\n", e, #[t: t in ORB[e] | t[1] ge 1];
    end if;
  end for;
end if;
print "PLACECOUNTS8_DONE"; quit;
