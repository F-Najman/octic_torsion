/* Exact two-coordinate inverse by prime-field linear algebra.
   Avoids constructing or embedding the subfield generated by one coordinate.
   The pair may lie in a proper subfield of its ambient finite field. */
function C48PairAFPlaceLinear(coords,values)
 assert #coords eq 2 and #values eq 2;
 K:=Parent(values[1]);assert Parent(values[2]) cmpeq K;
 k:=PrimeField(K);p:=#k;n:=Degree(K);
 e:=LCM([Degree(MinimalPolynomial(v,k)):v in values]);
 found:=false;
 for bits in [[1,0],[0,1]] cat [[1,a]:a in [1..p-1]] do
  gen:=&+[K!bits[i]*values[i]:i in [1..2]];pol:=MinimalPolynomial(gen,k);
  if Degree(pol) eq e then chosen:=bits;found:=true;break;end if;
 end for;
 assert found;
 M:=Matrix(k,[Eltseq(gen^i,k):i in [0..e-1]]);assert Rank(M) eq e;
 cs:=[Eltseq(Solution(M,Vector(k,Eltseq(v,k)))):v in values];
 assert &and[&+[K!cs[j][i+1]*gen^i:i in [0..e-1]] eq values[j]:j in [1,2]];
 F:=Parent(coords[1]);assert Parent(coords[2]) cmpeq F;
 gg:=&+[F!chosen[i]*coords[i]:i in [1,2]];
 fs:=[Evaluate(pol,gg)] cat [coords[j]-&+[F!cs[j][i+1]*gg^i:i in [0..e-1]]:j in [1,2]];
 O:=MaximalOrderFinite(F);I:=ideal<O|fs>;fa:=Factorization(I);
 ps:=[Place(z[1]):z in fa|z[2] gt 0];
 if #ps eq 0 then
  Oi:=MaximalOrderInfinite(F);Ii:=ideal<Oi|fs>;fai:=Factorization(Ii);
  ps:=[Place(z[1]):z in fai|z[2] gt 0];
 end if;
 assert #ps eq 1 and Degree(ps[1]) eq e;
 assert &and[f eq 0 or Valuation(f,ps[1]) gt 0:f in fs];
 return ps[1];
end function;
